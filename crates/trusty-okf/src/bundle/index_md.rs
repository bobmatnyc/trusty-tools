//! The OKF §8 `index.md` regenerator (moved role of trusty-kb
//! `structure.rs`, #10746; SPEC-OKF-01 §2.3, §2.7.2, §4.5).
//!
//! Why: `index.md` is a derived file, so regenerating it must be idempotent
//! (a second run writes zero bytes), and a hand-written `index.md` must
//! never be overwritten.
//! What: [`Bundle::regenerate_indexes`] writes one `index.md` per directory
//! that holds a concept at any depth, the root included. Each lists the
//! directory's concepts as `* [title](name.md) - description` (OKF §8) and
//! its subdirectories under `# Subdirectories`. Only the root `index.md`
//! carries frontmatter, and only `okf_version`. A file is overwritten only
//! when it is generated: its first line, or for the root the first line
//! after its frontmatter block, is [`GENERATED_MARKER`] or trusty-kb's
//! [`TRUSTY_KB_MARKER`]. Any other `index.md` stays byte-identical and earns
//! an info finding. Writes are compare-then-atomic, keeping the file mode.
//! Test: `c07_second_regenerate_writes_zero_bytes`,
//! `c08_hand_written_index_stays_byte_identical`,
//! `c115_bundle_open_reads_foreign_files_and_writes_never_touch_them`.

use std::collections::{BTreeMap, BTreeSet};

use serde_yaml::Value;

use crate::OkfError;
use crate::bundle::Bundle;
use crate::bundle::paths::{atomic_write, confined_file, io_err};
use crate::bundle::walk::scan;
use crate::format::concept::parse_concept;
use crate::format::id::{ConceptId, ConceptRef};
use crate::format::raw::split_raw;
use crate::format::validate::{Finding, FindingKind, Severity};

/// The first line of every `index.md` trusty-okf writes.
pub const GENERATED_MARKER: &str =
    "<!-- GENERATED by trusty-okf; do not edit — regenerate with Bundle::regenerate_indexes -->";

/// trusty-kb's generator marker (`structure.rs:22@c1eed98441`). An
/// `index.md` that starts with it is a derived file too (§2.3). trusty-kb
/// takes its own constant from here, so the two never drift.
pub const TRUSTY_KB_MARKER: &str =
    "<!-- GENERATED by trusty-kb; do not edit — regenerate with kb_ensure_structure -->";

/// The OKF version the root `index.md` declares (§2.3, §2.8).
pub const OKF_VERSION: &str = "0.2";

/// What `regenerate_indexes` did.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct IndexReport {
    /// Bundle-relative `index.md` paths written this run, sorted.
    pub written: Vec<String>,
    /// Generated files whose bytes were already current.
    pub unchanged: usize,
    /// Hand-written `index.md` paths left unchanged, sorted.
    pub kept: Vec<String>,
    /// One info finding per kept file.
    pub findings: Vec<Finding>,
}

/// One directory's listing.
#[derive(Default)]
struct Dir {
    concepts: Vec<(String, String, Option<String>)>,
    subdirs: BTreeSet<String>,
}

/// Whether `text` is a generated `index.md`.
fn is_generated(text: &str, root: bool) -> bool {
    let body = match (root, split_raw(text)) {
        (true, Some((end, _))) => &text[end..],
        _ => text,
    };
    let first = body.lines().next().unwrap_or("");
    first == GENERATED_MARKER || first == TRUSTY_KB_MARKER
}

/// One line of entry text: newlines folded to spaces, brackets escaped.
fn one_line(s: &str) -> String {
    s.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('[', "\\[")
        .replace(']', "\\]")
}

fn render(dir: &str, d: &Dir) -> String {
    let mut out = String::new();
    if dir.is_empty() {
        out.push_str(&format!("---\nokf_version: \"{OKF_VERSION}\"\n---\n"));
    }
    out.push_str(GENERATED_MARKER);
    let heading = dir
        .rsplit('/')
        .next()
        .filter(|h| !h.is_empty())
        .unwrap_or("Index");
    out.push_str(&format!("\n\n# {}\n", one_line(heading)));
    if !d.concepts.is_empty() {
        out.push('\n');
        for (name, title, description) in &d.concepts {
            match description {
                Some(desc) => out.push_str(&format!(
                    "* [{}]({name}) - {}\n",
                    one_line(title),
                    one_line(desc)
                )),
                None => out.push_str(&format!("* [{}]({name})\n", one_line(title))),
            }
        }
    }
    if !d.subdirs.is_empty() {
        out.push_str("\n# Subdirectories\n\n");
        for sub in &d.subdirs {
            out.push_str(&format!("* [{sub}]({sub}/index.md)\n"));
        }
    }
    out
}

impl Bundle {
    /// Regenerate every derived `index.md` (SPEC-OKF-01 §4.3).
    ///
    /// Why/What: see the module doc. The listing is sorted by file name and
    /// uses only concept frontmatter (`title`, else the file stem;
    /// `description`), so equal concepts give equal bytes. A concept whose
    /// frontmatter does not parse is listed by its stem. Foreign files are
    /// not listed. An `index.md` path that crosses a link is skipped with a
    /// warning.
    /// Test: `c07_second_regenerate_writes_zero_bytes`,
    /// `c08_hand_written_index_stays_byte_identical`.
    pub fn regenerate_indexes(&mut self) -> Result<IndexReport, OkfError> {
        let mut dirs: BTreeMap<String, Dir> = BTreeMap::new();
        for entry in scan(&self.root)?.files {
            let ConceptRef::Id(id) = entry.r else {
                continue;
            };
            let (dir, name) = id.file_name().rsplit_once('/').map_or_else(
                || (String::new(), id.file_name()),
                |(d, n)| (d.to_string(), n.to_string()),
            );
            let (title, description) = self.title_and_description(&id, &entry.rel);
            dirs.entry(dir.clone())
                .or_default()
                .concepts
                .push((name, title, description));
            // Every ancestor lists the next directory down.
            let mut child = dir;
            while !child.is_empty() {
                let (parent, last) = child
                    .rsplit_once('/')
                    .map_or((String::new(), child.clone()), |(p, l)| {
                        (p.to_string(), l.to_string())
                    });
                dirs.entry(parent.clone()).or_default().subdirs.insert(last);
                child = parent;
            }
        }
        let mut report = IndexReport::default();
        for (dir, d) in &dirs {
            let rel = if dir.is_empty() {
                "index.md".to_string()
            } else {
                format!("{dir}/index.md")
            };
            let path = match confined_file(&self.root, &rel) {
                Ok(p) => p,
                Err(OkfError::PathEscape(_)) => {
                    report.findings.push(Finding::new(
                        Severity::Warning,
                        FindingKind::SymlinkSkipped,
                        rel,
                        "index.md path crosses a symbolic link; not written".to_string(),
                        "SPEC-OKF-01 §2.11",
                    ));
                    continue;
                }
                Err(e) => return Err(e),
            };
            let content = render(dir, d);
            match std::fs::read(&path) {
                Ok(old) if old == content.as_bytes() => report.unchanged += 1,
                Ok(old) if !is_generated(&String::from_utf8_lossy(&old), dir.is_empty()) => {
                    report.findings.push(Finding::new(
                        Severity::Info,
                        FindingKind::HandWrittenIndex,
                        rel.clone(),
                        "index.md has no generator marker; left unchanged".to_string(),
                        "SPEC-OKF-01 §2.3",
                    ));
                    report.kept.push(rel);
                }
                Ok(_) => {
                    atomic_write(&path, content.as_bytes())?;
                    report.written.push(rel);
                }
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
                    atomic_write(&path, content.as_bytes())?;
                    report.written.push(rel);
                }
                Err(e) => return Err(io_err(&path, e)),
            }
        }
        report.written.sort();
        report.kept.sort();
        Ok(report)
    }

    /// The listing title and description of one concept file.
    fn title_and_description(&self, id: &ConceptId, rel: &str) -> (String, Option<String>) {
        let stem = id
            .as_str()
            .rsplit('/')
            .next()
            .unwrap_or(id.as_str())
            .to_string();
        let parsed = std::fs::read_to_string(self.root.join(rel))
            .ok()
            .and_then(|t| parse_concept(id.clone(), &t).ok());
        let Some((c, _)) = parsed else {
            return (stem, None);
        };
        let text = |k: &str| {
            c.get(k)
                .and_then(Value::as_str)
                .map(str::trim)
                .filter(|s| !s.is_empty())
        };
        (
            text("title").map_or(stem, str::to_string),
            text("description").map(str::to_string),
        )
    }
}
