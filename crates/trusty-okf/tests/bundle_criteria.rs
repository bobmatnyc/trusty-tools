/// Criterion 55: `move_concept` leaves a relative link that climbs above the
/// root unchanged and reports it.
#[test]
fn c55_move_leaves_a_climbing_link_and_reports_it() {
    let tmp = tempfile::tempdir().unwrap();
    let r = tmp.path();
    write(r, "a/x.md", "---\ntype: Note\n---\n");
    let linker = "---\ntype: Note\n---\n[out](../../outside/x.md) [in](../a/x.md)\n";
    write(r, "b/y.md", linker);
    let report = open(r).move_concept(&id("a/x"), &id("c/x"), now()).unwrap();
    let y = read(r, "b/y.md");
    assert!(y.contains("[out](../../outside/x.md)"), "{y}");
    assert!(y.contains("[in](/c/x.md)"), "{y}");
    assert!(report.unmoved.iter().any(|u| u.path == "b/y.md"
        && u.target == "../../outside/x.md"
        && u.reason == "climbs_above_root"));
}

/// Criterion 56: a `superseded_by` (or `supersedes`) value that does not
/// parse as a concept link is refused and the file is unchanged. The
/// `supersede` entry point (S6) writes through the same `put` check.
#[test]
fn c56_supersession_link_must_parse_as_a_concept_id() {
    let tmp = tempfile::tempdir().unwrap();
    let r = tmp.path();
    let text = "---\ntype: Note\n---\n";
    write(r, "old.md", text);
    let mut b = open(r);
    for bad in [
        "../../etc/passwd.md",
        "/_sources/x.md",
        "new",
        "/a/../b.md",
        "/index.md",
    ] {
        let mut c = b.get(&id("old")).unwrap();
        c.set("superseded_by", Value::String(bad.into()));
        let got = b.put(c, Actor::Process("t".into()), WriteMode::Lenient, now());
        assert!(
            matches!(got, Err(OkfError::InvalidId { .. })),
            "{bad}: {got:?}"
        );
        assert_eq!(read(r, "old.md"), text);
    }
    assert_eq!(link_target("/new/x.md").unwrap(), id("new/x"));
    let mut c = b.get(&id("old")).unwrap();
    c.set("superseded_by", Value::String("/new.md".into()));
    b.put(c, Actor::Process("t".into()), WriteMode::Lenient, now())
        .unwrap();
}

/// Criterion 57: no write path calls an HTTP route; the crate has no HTTP
/// client dependency. The boundary script checks the resolved graph (B8);
/// this checks the manifest and the source.
#[test]
fn c57_no_http_client_dependency() {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let manifest = std::fs::read_to_string(dir.join("Cargo.toml")).unwrap();
    for dep in [
        "reqwest",
        "hyper",
        "ureq",
        "isahc",
        "surf",
        "curl",
        "attohttpc",
        "minreq",
    ] {
        assert!(
            !manifest.lines().any(|l| l.trim_start().starts_with(dep)),
            "{dep} in Cargo.toml"
        );
    }
    let mut stack = vec![dir.join("src")];
    while let Some(d) = stack.pop() {
        for e in std::fs::read_dir(d).unwrap() {
            let p = e.unwrap().path();
            if p.is_dir() {
                stack.push(p);
            } else {
                let text = std::fs::read_to_string(&p).unwrap();
                for token in ["http://", "TcpStream", "std::net"] {
                    assert!(!text.contains(token), "{p:?} holds {token}");
                }
            }
        }
    }
}

/// Criterion 115 (S3 part): a bundle with `notes/a:b.md`, `Index.md` and
/// `_drafts/x.md` opens with one info finding per file; after
/// `regenerate_indexes` and a `move_concept` of a concept they link to, the
/// three files are byte-identical; a put to one is `InvalidId`. `rebuild`
/// is S6.
#[test]
fn c115_bundle_open_reads_foreign_files_and_writes_never_touch_them() {
    let tmp = tempfile::tempdir().unwrap();
    let r = tmp.path();
    let text = "---\ntype: Note\n---\n\nSee [target](/notes/target.md).\n";
    let foreign = ["notes/a:b.md", "Index.md", "_drafts/x.md"];
    for rel in foreign {
        write(r, rel, text);
    }
    write(r, "notes/target.md", "---\ntype: Note\n---\n");
    let (mut b, findings) = Bundle::open(r).unwrap();
    for rel in foreign {
        let n = findings
            .iter()
            .filter(|f| f.path == rel && f.kind == FindingKind::ForeignPath)
            .count();
        assert_eq!(n, 1, "{rel}: {findings:?}");
    }
    b.regenerate_indexes().unwrap();
    let report = b
        .move_concept(&id("notes/target"), &id("notes/moved"), now())
        .unwrap();
    for rel in foreign {
        assert_eq!(read(r, rel), text, "{rel}");
        assert!(
            report
                .unmoved
                .iter()
                .any(|u| u.path == rel && u.reason == "foreign_file")
        );
    }
    let (c, _) = parse_concept(id("notes/ok"), text).unwrap();
    let mut foreign_c = c.clone();
    foreign_c.id = trusty_okf::format::ConceptRef::Foreign("notes/a:b.md".into());
    let got = b.put(
        foreign_c,
        Actor::Process("t".into()),
        WriteMode::Lenient,
        now(),
    );
    assert!(
        matches!(got, Err(OkfError::InvalidId { rule: 4, .. })),
        "{got:?}"
    );
}

/// Criterion 140: with `Notes/A` present, `put("notes/a")` and a move to
/// `notes/a` return `Conflict { reason: "fold_collision" }` and change no
/// file; the same for an NFD spelling of an NFC ID. The rule reads directory
/// listings lexically, so it gives the same result on case-sensitive and
/// case-insensitive file systems; the test logs which one it ran on.
#[test]
fn c140_fold_collision_on_put_and_move() {
    let tmp = tempfile::tempdir().unwrap();
    let r = tmp.path();
    write(r, "Notes/A.md", "---\ntype: Note\n---\n");
    write(r, "caf\u{e9}.md", "---\ntype: Note\n---\n");
    write(r, "other.md", "---\ntype: Note\n---\n");
    let insensitive = r.join("notes/a.md").exists();
    eprintln!("c140: case-insensitive file system: {insensitive}");
    let before = tree(r);
    let mut b = open(r);
    let fold = |got: Result<_, OkfError>| matches!(got, Err(OkfError::Conflict { ref reason, .. }) if reason == "fold_collision");
    for target in ["notes/a", "cafe\u{301}"] {
        let mut values = serde_yaml::Mapping::new();
        values.insert("type".into(), "Note".into());
        let c = Concept::new(id(target), values, String::new());
        let got = b.put(c, Actor::Process("t".into()), WriteMode::default(), now());
        assert!(fold(got.map(|_| ())), "put {target}");
        let got = b.move_concept(&id("other"), &id(target), now());
        assert!(fold(got.map(|_| ())), "move to {target}");
    }
    assert_eq!(tree(r), before, "no file changed");
}
